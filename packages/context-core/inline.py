#!/usr/bin/env python3
"""Puts the package inside the plugin scripts that use it, so each one keeps working when downloaded alone.

Every script that has moved onto the package carries a region between `BEGIN` and `END`; this fills it with the
sources of the modules the scripts reach, as strings loaded into `sys.modules` under `context_core`: `compat`, which is
all the scripts import, and what it imports, followed through the package (`reachable()`; today language, records, rules
and compat, not parse, load or storage). The committed scripts carry the region already filled, because the sessions
download them from the repository tag and check their hash: what is in the repository is what runs.

The region knows the SHA-256 of each source it carries. If a `context_core` is already loaded in the process (another
script's region, or the installed package), it is used only if its modules have the same fingerprints; otherwise the
script stops with an ImportError instead of running on whichever copy loaded first (review of 1.25.2, finding 6).

    python3 packages/context-core/inline.py            # rewrite the region of every script that has one
    python3 packages/context-core/inline.py --check    # exit 1 if any region is not what the package says (tests and release.sh)
"""
import ast, hashlib, pathlib, re, sys

CORE = pathlib.Path(__file__).resolve().parent
REPO = CORE.parent.parent
ENTRY = "compat"   # what the scripts import


def reachable(entry: str = ENTRY) -> list:
    """The package modules `entry` imports, directly or not, in an order that loads each after what it imports."""
    out, seen = [], set()

    def visit(m):
        if m in seen:
            return
        seen.add(m)
        tree = ast.parse((CORE / "context_core" / f"{m}.py").read_text(encoding="utf-8"))
        for node in ast.walk(tree):
            if isinstance(node, ast.ImportFrom) and node.level == 1:
                for dep in ([node.module.split(".")[0]] if node.module else [a.name for a in node.names]):
                    visit(dep)
        out.append(m)

    visit(entry)
    return out


MODULES = reachable()
BEGIN = "# --- context_core: generated by packages/context-core/inline.py from packages/context-core/context_core; do not edit by hand ---"
END = "# --- end of context_core ---"
PL = REPO / "plugins" / "memoria"
SCRIPTS = [PL / "skills/sesion/abrir.py", PL / "skills/sesion/cerrar.py", PL / "skills/sesion/permisos.py",
           PL / "skills/sesion/migrar_estructura.py", PL / "skills/tablero/aplicar_cambios.py",
           PL / "skills/tablero/generar_vista.py", PL / "skills/tablero/barrido.py", PL / "verificar.sh"]


def fingerprint(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def region() -> str:
    src = {m: (CORE / "context_core" / f"{m}.py").read_text(encoding="utf-8") for m in MODULES}
    # one short ASCII literal per source line: Python 3.9's tokenizer misreads very long lines with non-ASCII characters
    # («Non-UTF-8 code»), which is what each person's Mac runs
    lit = lambda text: "(\n" + "".join(f"        {ascii(l)}\n" for l in text.splitlines(keepends=True)) + "    )"
    body = ",\n".join(f"    {m!r}: {lit(src[m])}" for m in MODULES)
    fps = "".join(f"    {m!r}: {fingerprint(src[m])!r},\n" for m in MODULES)
    return f'''{BEGIN}
def _context_core():
    import sys as _s, types as _t
    _fp = {{
{fps}    }}
    _pkg, _todo = _s.modules.get("context_core"), list(_fp)
    if _pkg is not None:
        # already loaded (another script's region, or the installed package): only if it is this same code
        import hashlib as _h, importlib as _i
        _todo = []
        for _n in _fp:
            _m = _s.modules.get("context_core." + _n)
            if _m is None and getattr(_pkg, "__path__", None):
                _m = _i.import_module("context_core." + _n)
            if _m is None:
                _todo.append(_n); continue
            _got = getattr(_m, "__fingerprint__", None)
            if _got is None and getattr(_m, "__file__", None):
                with open(_m.__file__, encoding="utf-8") as _f:
                    _got = _h.sha256(_f.read().encode("utf-8")).hexdigest()
            if _got != _fp[_n]:
                raise ImportError("context_core." + _n + " is already loaded in this process from another version of the package"
                                  " than the one inlined in " + str(globals().get("__file__") or _s.argv[0]) + ": run each in its own process")
        if not _todo:
            return
    else:
        _pkg = _t.ModuleType("context_core"); _pkg.__path__ = []; _s.modules["context_core"] = _pkg
    _src = {{
{body},
    }}
    for _n in _todo:
        _m = _t.ModuleType("context_core." + _n); _m.__package__ = "context_core"; _m.__fingerprint__ = _fp[_n]
        _s.modules[_m.__name__] = _m
        exec(compile(_src[_n], "<context_core/" + _n + ".py>", "exec"), _m.__dict__)
        setattr(_pkg, _n, _m)
_context_core()
{END}'''


def apply(text: str) -> str:
    a, b = text.index(BEGIN), text.index(END) + len(END)
    return text[:a] + region() + text[b:]


def unlisted() -> list:
    """Files of the plugin that use context_core but are not in SCRIPTS: they would pass every check and fail with
    «No module named 'context_core'» on each person's computer (review of 1.25.2, finding 5)."""
    out = []
    for p in sorted((REPO / "plugins").rglob("*")):
        if p.is_file() and p.suffix in (".py", ".sh") and p not in SCRIPTS:
            t = p.read_text(encoding="utf-8", errors="replace")
            if re.search(r"^\s*(?:from|import)\s+context_core\b", t, re.M):
                out.append(p.relative_to(REPO))
    return out


def main(argv):
    check = "--check" in argv
    stray = unlisted()
    if stray:
        print("these files use context_core and inline.py does not fill them: " + ", ".join(map(str, stray))
              + " (add them to SCRIPTS with a region)")
        return 1
    stale = []
    for p in SCRIPTS:
        t = p.read_text(encoding="utf-8")
        new = apply(t)
        if new != t:
            stale.append(p.relative_to(REPO))
            if not check:
                p.write_text(new, encoding="utf-8")
    if check and stale:
        print("context_core is out of date in: " + ", ".join(map(str, stale)) + " (run packages/context-core/inline.py)")
        return 1
    print(("up to date" if check else "rewritten: " + (", ".join(map(str, stale)) or "nothing")))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
