def con_diseno(gh, diseno, migraciones_extra):
    """Lo que no está en el diseño: tablas nuevas que no están en «Datos», código nuevo fuera de los «Dónde vive» de
    «Componentes» y nombres que el diseño dice que no son un concepto («No es»)."""
    out = {"tablas": [], "fuera_de_componentes": [], "alias": []}
    entidades = {key(e.name) for e in diseno.entities} | {key(e.name) + "s" for e in diseno.entities} | \
                {key(e.name) + "es" for e in diseno.entities}
    alias = {}
    for c in diseno.concepts:
        for a in c.get("no_es", []):
            if key(a):
                alias[key(a)] = (a, c.get("concepto", ""))
    rutas = {}
    for c in diseno.components:
        m = re.match(r"^([\w.-]+/[\w.-]+)(?::(.*))?$", (c.get("donde_vive") or "").strip())
        if m:
            rutas.setdefault(m.group(1).lower(), []).append((m.group(2) or "").strip().strip("/"))
    for r in gh.get("repos", []):
        nombre = r["repo"]
        extra = [re.compile(re.escape(x.strip("/")) + r"/") for x in migraciones_extra]
        sueltos = set()
        for d in r.get("detalle", []):
            for f in d.get("files", []):
                fn = f.get("filename", "")
                es_mig = MIGRACION.search(fn) or any(x.match(fn) for x in extra)
                anadidas = "\n".join(l[1:] for l in (f.get("patch") or "").split("\n") if l.startswith("+") and not l.startswith("+++"))
                if es_mig and f.get("status") == "added":
                    for t in re.findall(r"create\s+table\s+(?:if\s+not\s+exists\s+)?(?:[\w\"]+\.)?\"?(\w+)\"?", anadidas, re.I):
                        if key(t) not in entidades and diseno.entities is not None:
                            out["tablas"].append({"repo": nombre, "tabla": t, "archivo": fn, "commit": corto(d["sha"])})
                if f.get("status") == "added" and nombre.lower() in rutas and not IGNORADAS.match(fn) and "/" in fn and not es_mig:
                    if not any(not p or fn == p or fn.startswith(p + "/") for p in rutas[nombre.lower()]):
                        sueltos.add("/".join(fn.split("/")[:2 if fn.count("/") > 1 else 1]))
                if alias and anadidas and not fn.lower().endswith((".md", ".lock")):
                    palabras = set(re.findall(r"[A-Za-zÀ-ÿ_]+", anadidas))
                    trozos = set()
                    for w in palabras:
                        trozos.add(key(w))
                        trozos.update(key(x) for x in re.split(r"_|(?<=[a-z])(?=[A-Z])", w) if x)
                    for k, (a, concepto) in alias.items():
                        if k in trozos:
                            out["alias"].append({"repo": nombre, "alias": a, "concepto": concepto, "archivo": fn, "commit": corto(d["sha"])})
        out["fuera_de_componentes"] += [{"repo": nombre, "ruta": s} for s in sorted(sueltos)]
    # una sola vez cada cosa
    for k in out:
        vistos, unicos = set(), []
        for x in out[k]:
            sig = tuple(sorted((a, b) for a, b in x.items() if a not in ("commit",)))
            if sig not in vistos:
                vistos.add(sig)
                unicos.append(x)
        out[k] = unicos
    return out


def reglas(gh, sec, forma):
    """Lo que rompe las reglas imprescindibles desde --desde: commits en la rama principal sin pull request, uniones sin
    squash, migraciones ya unidas que cambiaron, cambios al CLAUDE.md o a los controles, y pasos a Prod sin sí o que
    aprobó quien construyó."""
    out = {"sin_pr": [], "sin_squash": [], "migraciones": [], "controles": [], "prod_sin_si": [], "si_propio": []}
    desde = gh.get("desde", "")
    construye = {p.user.lower(): p for p in sec.roles.get("Construye", []) if p.user}
    for r in gh.get("repos", []):
        nombre = r["repo"]
        unidos = {p["merge_commit"]: p for p in r.get("pulls", []) if p.get("state") == "merged" and p.get("merge_commit")}
        commits = {c["sha"]: c for c in r.get("commits", [])}
        for c in r.get("commits", []):
            if (c.get("date") or "")[:10] < desde:
                break
            if c["sha"] not in unidos:
                out["sin_pr"].append({"repo": nombre, "commit": corto(c["sha"]), "mensaje": c.get("message", "")})
            elif c.get("parents", 1) > 1:
                out["sin_squash"].append({"repo": nombre, "commit": corto(c["sha"]), "pr": unidos[c["sha"]]["number"]})
        for d in r.get("detalle", []):
            pr = unidos.get(d["sha"])
            for f in d.get("files", []):
                fn = f.get("filename", "")
                if MIGRACION.search(fn) and f.get("status") in ("modified", "removed", "renamed"):
                    out["migraciones"].append({"repo": nombre, "archivo": f.get("previous_filename") or fn, "como": f["status"],
                                               "commit": corto(d["sha"]), "pr": pr["number"] if pr else None})
                if CONTROLES.search(fn):
                    out["controles"].append({"repo": nombre, "archivo": fn, "commit": corto(d["sha"]), "pr": pr["number"] if pr else None})
        pos = historia(r)
        pasos = pasos_a_prod(r, forma)
        for i, paso in enumerate(pasos):
            if paso["fecha"] and paso["fecha"] < desde:
                continue
            if key(forma) == key("release de GitHub") and paso["release"] and not paso["aprobo"]:
                out["prod_sin_si"].append({"repo": nombre, "tag": paso["tag"], "commit": corto(paso["sha"])})
            if paso["aprobo"]:
                # los pull requests que entraron en este paso: entre el anterior y este
                hasta = pos.get(paso["sha"])
                antes = next((pos.get(p["sha"]) for p in pasos[i + 1:] if pos.get(p["sha"]) is not None), None)
                for p in r.get("pulls", []):
                    m = pos.get(p.get("merge_commit") or "")
                    if p.get("state") != "merged" or m is None or hasta is None or m < hasta or (antes is not None and m >= antes):
                        continue
                    quien = construye.get((p.get("author") or "").lower())
                    if quien and nombre_key(quien.name) == nombre_key(paso["aprobo"]["quien"]):
                        out["si_propio"].append({"repo": nombre, "tag": paso["tag"], "pr": p["number"], "quien": quien.name})
    return out


