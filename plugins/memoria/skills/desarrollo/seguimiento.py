def _reglas_de_la_rama(au, rama):
    """(exige pull request, sin excepciones (True, False o None si la cuenta no ve las excepciones), métodos de unión,
    comprobaciones obligatorias, comprobaciones sin excepciones (igual), evidencia, lo que no se ve)."""
    ev, no_ve = [], []
    pr, pr_sin, metodos, checks, checks_sin = False, False, None, [], False   # False: no data yet, or bypassable
    for rs in au.get("rulesets") or []:
        if rs.get("enforcement") != "active" or rs.get("target", "branch") != "branch":
            continue
        inc = ((rs.get("conditions") or {}).get("ref_name") or {}).get("include") or []
        if not any(x in ("~DEFAULT_BRANCH", "~ALL", f"refs/heads/{rama}") for x in inc):
            continue
        # GitHub da «bypass_actors» solo a quien puede escribir el ruleset: sin la clave, no se sabe (hallazgo 1)
        sin_bypass = (not rs["bypass_actors"]) if isinstance(rs.get("bypass_actors"), list) else None   # nulo, como ausente
        if sin_bypass is None:
            no_ve.append(f"las excepciones del ruleset «{rs.get('name')}»")
        for regla in rs.get("rules") or []:
            if regla.get("type") == "pull_request":
                pr = True
                pr_sin = True if (pr_sin is True or sin_bypass is True) else (None if (pr_sin is None or sin_bypass is None) else False)
                metodos = (regla.get("parameters") or {}).get("allowed_merge_methods") or metodos
                ev.append(f"ruleset «{rs.get('name')}» exige pull request" + {True: " sin excepciones", False: ", con excepciones", None: ""}[sin_bypass])
            if regla.get("type") == "required_status_checks":
                checks += [c.get("context") for c in (regla.get("parameters") or {}).get("required_status_checks") or []]
                checks_sin = True if (checks_sin is True or sin_bypass is True) else (None if (checks_sin is None or sin_bypass is None) else False)
                ev.append(f"ruleset «{rs.get('name')}» exige comprobaciones" + {True: " sin excepciones", False: ", con excepciones", None: ""}[sin_bypass])
    pro = au.get("proteccion") or {}
    if pro:
        admins = ((pro.get("enforce_admins") or {}).get("enabled")) is True
        if pro.get("required_pull_request_reviews") is not None:
            pr = True
            pr_sin = True if admins else pr_sin
            ev.append("la protección clásica exige pull request" + ("" if admins else ", y los administradores se la pueden saltar"))
        rsc = (pro.get("required_status_checks") or {}).get("contexts") or []
        if rsc:
            checks += rsc
            checks_sin = True if admins else checks_sin
            ev.append("la protección clásica exige " + ", ".join(rsc) + ("" if admins else
                      "; sin «Do not allow bypassing the above settings», un administrador puede unir con ellas en rojo"))
    elif "proteccion" in (au.get("errores") or {}) and "404" not in (au.get("errores") or {}).get("proteccion", ""):
        no_ve.append("la protección clásica de la rama")
    return pr, pr_sin, metodos, list(dict.fromkeys(c for c in checks if c)), checks_sin, ev, no_ve


