def cmd_auditoria(a):
    raiz, proyecto = a["pos"][0], a["pos"][1].strip("/")
    tp, sec, textos = kit(raiz, proyecto)
    gh = json.load(open(a["github"], encoding="utf-8"))
    fecha = a["fecha"]
    res = {"fecha": fecha, "comprobado": {}, "preguntar": [], "si_propio": []}
    poner = lambda fila, col, est, ev: res["comprobado"].setdefault(fila, {}).__setitem__(col, {"estado": est, "evidencia": ev})
    plan = leer_plan(textos["Plan"][1]) if "Plan" in textos else None
    hace31 = (datetime.date.fromisoformat(fecha) - datetime.timedelta(days=31)).isoformat()
    orgs = {}
    for r in gh.get("repos", []):
        nombre = r["repo"]
        au = r.get("auditoria")
        if r.get("error") or not au:
            for f in ("R1", "R2", "R3", "R6"):
                res["preguntar"].append({"fila": f, "columna": nombre, "porque": r.get("error") or "sin datos de la auditoría"})
            continue
        rep = au.get("repo") or {}
        pr_sin, metodos, checks, checks_sin, ev = _reglas_de_la_rama(au, rep.get("default_branch") or r.get("rama") or "main")
        solo_squash = rep.get("allow_squash_merge") is True and not rep.get("allow_merge_commit") and not rep.get("allow_rebase_merge")
        if metodos:
            solo_squash = solo_squash or metodos == ["squash"]
        if not au.get("rulesets") and not au.get("proteccion") and au.get("errores"):
            res["preguntar"].append({"fila": "R1", "columna": nombre, "porque": "; ".join(au["errores"].values())})
            res["preguntar"].append({"fila": "R2", "columna": nombre, "porque": "; ".join(au["errores"].values())})
        else:
            poner("R1", nombre, "cumple" if pr_sin and solo_squash else "no cumple",
                  "; ".join([e for e in ev if "pull request" in e] + [("solo squash" if solo_squash else "se puede unir sin squash")])
                  + ("" if pr_sin else "; la rama principal no exige pull request sin excepciones"))
            poner("R2", nombre, "cumple" if checks and checks_sin else "no cumple",
                  "; ".join(e for e in ev if "pull request" not in e) or "no hay comprobaciones obligatorias")
        sec_an = (rep.get("security_and_analysis") or {})
        push = ((sec_an.get("secret_scanning_push_protection") or {}).get("status")) == "enabled"
        check_sec = [c for c in checks if "secret" in key(c) or "secreto" in key(c)]
        if push or check_sec:
            poner("R3", nombre, "cumple", "; ".join(([f"comprobación obligatoria {', '.join(check_sec)}"] if check_sec else [])
                                                   + (["la protección de secretos al subir está activa"] if push else [])))
        elif sec_an or checks:
            poner("R3", nombre, "no cumple", "ni comprobación de secretos obligatoria ni protección de secretos al subir")
        else:
            res["preguntar"].append({"fila": "R3", "columna": nombre, "porque": "la cuenta no ve la seguridad del repositorio"})
        if plan is not None:
            fuera = [p for p in estado_piezas(plan, [x for x in prs_de({"repos": [r]})]).outside_plan
                     if p.state == "merged" and next((q for q in r.get("pulls", []) if q["number"] == p.number), {}).get("merged_at", "")[:10] >= hace31]
            poner("R6", nombre, "cumple" if not fuera else "no cumple",
                  "todos los pull requests unidos en el último mes llevan su pieza" if not fuera else
                  "sin pieza: " + ", ".join(f"#{p.number}" for p in fuera[:10]))
        org = nombre.split("/")[0]
        if org not in orgs:
            orgs[org] = (au.get("org"), au.get("admins"), au.get("errores") or {}, rep.get("private"))
    for org, (o, admins, err, privado) in orgs.items():
        if o:
            dos = o.get("two_factor_requirement_enabled") is True
            plan_ok = not (privado and (o.get("plan") or "").lower() == "free")
            poner("PL1", "Estado", "cumple" if dos and plan_ok else "no cumple",
                  f"{org}: verificación en dos pasos {'obligatoria' if dos else 'no obligatoria'}, plan {o.get('plan') or '?'}")
        else:
            res["preguntar"].append({"fila": "PL1", "columna": "Estado", "porque": err.get("org") or "no se pudo leer la organización"})
        if admins is not None:
            poner("PL2", "Estado", "cumple" if len(admins) >= 2 else "no cumple", f"{org}: {len(admins)} owners ({', '.join(admins)})")
        else:
            res["preguntar"].append({"fila": "PL2", "columna": "Estado", "porque": err.get("admins") or "no se pudieron leer los owners"})
    for f in ("PL3", "PL4", "PL5", "PL6", "PL7"):
        res["preguntar"].append({"fila": f, "columna": "Estado", "porque": "no se comprueba por la API de GitHub"})
    for r in gh.get("repos", []):
        for f in ("R4", "R5", "R7"):
            res["preguntar"].append({"fila": f, "columna": r["repo"], "porque": {"R4": "el último seguimiento lista las migraciones unidas que cambiaron",
                                                                              "R5": "quién puede desplegar en Prod no está en GitHub",
                                                                              "R7": "se mira el CLAUDE.md del repositorio"}[f]})
    gh_mes = dict(gh, desde=hace31)
    res["si_propio"] = reglas(gh_mes, sec, sec.step_to_prod or "")["si_propio"]
    for f, cols in res["comprobado"].items():
        for v in cols.values():
            v["regla"] = REGLAS.get(f, "")
    for x in res["preguntar"]:
        x["regla"] = REGLAS.get(x["fila"], "")
    print(json.dumps(res, ensure_ascii=False, indent=1))
    return 0


def cmd_aplicar(a):
    ruta, estados = a["pos"][0], json.load(open(a["pos"][1], encoding="utf-8"))
    texto = leer(ruta)
    if texto is None:
        raise SystemExit(f"no se pudo leer {ruta}")
    conf = leer_configuracion(texto)
    if not conf.kind:
        raise SystemExit(f"{ruta} no tiene la tabla con la columna «#»: no es una configuración del kit")
    lineas = texto.split("\n")
    cab = None
    cambiadas = []
    for i, l in enumerate(lineas):
        s = l.strip()
        if not s.startswith("|"):
            cab = None if cab is not None and not s else cab
            continue
        celdas = [c.strip() for c in s.strip("|").split("|")]
        if cab is None:
            if key(celdas[0]) == "":
                cab = celdas
            continue
        if re.match(r"^\|[\s:|-]+\|?$", s):
            continue
        fila = celdas[0].replace("`", "").replace("**", "").strip().upper()
        if fila not in estados:
            continue
        val = estados[fila]
        val = {"Estado": val} if isinstance(val, str) else val
        for col, est in val.items():
            j = next((j for j, h in enumerate(cab) if key(h) == key(col)), None)
            if j is None or j >= len(celdas):
                raise SystemExit(f"{fila}: no hay columna «{col}» en {ruta}")
            est_k = key(est.split("·")[0])
            if est_k not in (key("cumple"), key("no cumple"), key("no aplica"), key("excepción")):
                raise SystemExit(f"{fila}, {col}: «{est}» no es cumple, no cumple, no aplica ni excepción")
            celdas[j] = est.split("·")[0].strip() + (f" · {a['fecha']}" if est_k in (key("cumple"), key("no cumple")) else "")
            cambiadas.append(f"{fila} {col}")
        lineas[i] = "| " + " | ".join(celdas) + " |"
    nuevo = "\n".join(lineas)
    nuevo = re.sub(r"^actualizado:.*$", f"actualizado: {a['fecha']}", nuevo, count=1, flags=re.M)
    tmp = pathlib.Path(ruta).with_name("." + pathlib.Path(ruta).name + ".tmp")
    tmp.write_text(nuevo, encoding="utf-8")
    os.replace(tmp, ruta)
    print(json.dumps({"escrito": ruta, "celdas": cambiadas}, ensure_ascii=False))
    return 0


def main(argv):
    if not argv or argv[0] not in ("seguimiento", "auditoria", "aplicar"):
        print(__doc__, file=sys.stderr)
        return 2
    a = {"pos": [], "migraciones": []}
    i = 1
    while i < len(argv):
        x = argv[i]
        if x in ("--github", "--pidio", "--fecha"):
            a[x[2:]] = argv[i + 1]; i += 2; continue
        if x == "--migraciones":
            a["migraciones"].append(argv[i + 1]); i += 2; continue
        if x == "--escribir":
            a["escribir"] = True; i += 1; continue
        a["pos"].append(x); i += 1
    a.setdefault("fecha", datetime.date.today().isoformat())
    if not re.match(r"^20\d\d-\d\d-\d\d$", a["fecha"]):
        print("--fecha va como AAAA-MM-DD, la de hoy en la zona de la organización (la línea HOY de abrir.py)", file=sys.stderr)
        return 2
    need = {"seguimiento": 2, "auditoria": 2, "aplicar": 2}[argv[0]]
    if len(a["pos"]) < need:
        print(__doc__, file=sys.stderr)
        return 2
    return {"seguimiento": cmd_seguimiento, "auditoria": cmd_auditoria, "aplicar": cmd_aplicar}[argv[0]](a)


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
