def kit(raiz, proyecto):
    raiz = pathlib.Path(raiz)
    tp = leer(raiz / proyecto / "proyecto.md")
    if tp is None:
        raise SystemExit(f"no se pudo leer {proyecto}/proyecto.md")
    sec = seccion_desarrollo(tp)
    if not sec.found:
        raise SystemExit(f"{proyecto} no es un proyecto de desarrollo: su proyecto.md no tiene la sección «## Desarrollo»")
    textos = {}
    for k, r in sec.paths.items():
        if r and r != TO_BUILD and ".." not in r.split("/"):
            t = leer(raiz / r)
            if t is not None:
                textos[k] = (r, t)
    return tp, sec, textos


def ultimo_seguimiento(texto):
    m = re.search(r"^## .*?\b(20\d\d-\d\d-\d\d)\b", cabecera(texto or "")[1], re.M)
    return m.group(1) if m else ""


