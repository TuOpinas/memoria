def completo(r, que):
    """Si la lista `que` («pulls», «commits», «detalle», «tags», «releases») de un repositorio se leyó entera."""
    cortado = r.get("truncado") or []
    if que == "detalle" and any(x.startswith("archivos de ") for x in cortado):
        return False
    return not r.get("error") and que not in (r.get("errores") or {}) and que not in cortado


def prs_de(gh):
    """Los pull requests de GitHub, sin los que no dicen su rama base: sin ella no se sabe si cuentan (decisión -12)."""
    out, sin_base = [], []
    for r in gh.get("repos", []):
        for p in r.get("pulls", []):
            if not p.get("base"):
                sin_base.append(f"{r['repo']}#{p.get('number')}")
                continue
            out.append(PullRequest(repo=r["repo"], number=int(p["number"]), title=p.get("title") or "", state=p.get("state") or "",
                                   author=p.get("author") or "", bot=bool(p.get("bot")), merge_commit=p.get("merge_commit") or "",
                                   to_main=p.get("base") == r.get("rama", "main"), merged_at=p.get("merged_at") or ""))
    return out, sin_base


def historia(r):
    """{sha: posición} de la rama principal, 0 el más nuevo."""
    return {c["sha"]: i for i, c in enumerate(r.get("commits", []))}


def aprobado(rel):
    """El «Aprobó:» de un release, en su misma línea y con algo detrás; None si no lo hay."""
    m = APROBO.search(rel.get("body") or "")
    if not m:
        return None
    t = m.group(1).strip()
    quien = re.split(r",|·", t)[0].strip()
    if not quien:
        return None
    seg = re.search(r"seguimiento\s+(20\d\d-\d\d-\d\d)", t, re.I)
    return {"quien": quien, "texto": t, "seguimiento": seg.group(1) if seg else ""}


def es_release(forma):
    return key(forma) == key("release de GitHub")


def sin_forma(forma):
    return not (forma or "").strip() or key(forma) == key(TO_BUILD)


def pasos_a_prod(r, forma):
    """Los pasos a Prod de un repositorio, del más nuevo al más viejo: [{tag, sha, aprobo, fecha, release}]. Sin forma, ninguno.
    Con «release de GitHub», los releases publicados que no son prerelease; con otra forma, también las etiquetas, que es lo
    único que deja ver qué se desplegó, salvo las de una candidata («-rc», «-beta»…)."""
    if sin_forma(forma):
        return []
    pos = historia(r)
    out = []
    for x in r.get("releases", []):
        if x.get("draft") or x.get("prerelease") or not x.get("sha"):
            continue
        out.append({"tag": x["tag"], "sha": x["sha"], "aprobo": aprobado(x), "fecha": (x.get("published_at") or "")[:10],
                    "release": True, "autor": x.get("author", "")})
    if not es_release(forma):
        vistos = {o["sha"] for o in out}
        for t in r.get("tags", []):
            if t.get("sha") and t["sha"] not in vistos and not re.search(r"-(rc|beta|alpha|pre)", t.get("name", ""), re.I):
                out.append({"tag": t["name"], "sha": t["sha"], "aprobo": None, "fecha": "", "release": False, "autor": ""})
                vistos.add(t["sha"])
    out.sort(key=lambda o: (pos.get(o["sha"], 10 ** 9), "" if o["fecha"] else "~"))
    return out


def si_valido(paso, sec):
    """Si el sí de un paso a Prod vale: un «Aprobó:» de alguien de «Acepta» o «Audita»."""
    return bool(paso["aprobo"]) and persona(sec, paso["aprobo"]["quien"], ("Acepta", "Audita")) is not None


def entregados(gh, sec):
    """{repo: números de los pull requests unidos dentro del último paso a Prod}. Con «release de GitHub», solo cuenta un
    release con un sí válido. Un pull request unido antes de la ventana de commits leída cuenta si se unió antes del paso
    (revisión de la 1.27.0, hallazgo 7)."""
    forma = sec.step_to_prod or ""
    out = {}
    for r in gh.get("repos", []):
        pasos = [p for p in pasos_a_prod(r, forma) if not es_release(forma) or si_valido(p, sec)]
        pos = historia(r)
        if not pasos:
            continue
        paso = pasos[0]
        corte = pos.get(paso["sha"])
        fecha_paso = next((c["date"] for c in r.get("commits", []) if c["sha"] == paso["sha"]), "") or paso["fecha"]
        nums = []
        for p in r.get("pulls", []):
            if p.get("state") != "merged":
                continue
            m = pos.get(p.get("merge_commit") or "")
            if m is not None and corte is not None:
                if m >= corte:
                    nums.append(p["number"])
            elif m is None and fecha_paso and (p.get("merged_at") or "") and p["merged_at"] <= fecha_paso:
                nums.append(p["number"])        # unido antes de la ventana leída y antes del paso
        out[r["repo"]] = nums
    return out


