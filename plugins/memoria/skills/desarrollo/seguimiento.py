def _reglas_de_la_rama(au, rama):
    """(exige pull request sin excepciones, métodos de unión permitidos o None, comprobaciones obligatorias, sin excepciones
    para las comprobaciones, evidencia)."""
    ev, pr_sin, metodos, checks, checks_sin = [], False, None, [], False
    for rs in au.get("rulesets") or []:
        if rs.get("enforcement") != "active" or rs.get("target", "branch") != "branch":
            continue
        inc = ((rs.get("conditions") or {}).get("ref_name") or {}).get("include") or []
        if not any(x in ("~DEFAULT_BRANCH", "~ALL", f"refs/heads/{rama}") for x in inc):
            continue
        sin_bypass = not rs.get("bypass_actors")
        for regla in rs.get("rules") or []:
            if regla.get("type") == "pull_request":
                pr_sin = pr_sin or sin_bypass
                metodos = (regla.get("parameters") or {}).get("allowed_merge_methods") or metodos
                ev.append(f"ruleset «{rs.get('name')}» exige pull request" + ("" if sin_bypass else ", con excepciones"))
            if regla.get("type") == "required_status_checks":
                checks += [c.get("context") for c in (regla.get("parameters") or {}).get("required_status_checks") or []]
                checks_sin = checks_sin or sin_bypass
                ev.append(f"ruleset «{rs.get('name')}» exige comprobaciones" + ("" if sin_bypass else ", con excepciones"))
    pro = au.get("proteccion") or {}
    if pro:
        admins = ((pro.get("enforce_admins") or {}).get("enabled")) is True
        if pro.get("required_pull_request_reviews") is not None:
            pr_sin = pr_sin or admins
            ev.append("la protección clásica exige pull request" + ("" if admins else ", y los administradores se la pueden saltar"))
        rsc = (pro.get("required_status_checks") or {}).get("contexts") or []
        if rsc:
            checks += rsc
            checks_sin = checks_sin or admins
            ev.append("la protección clásica exige " + ", ".join(rsc) + ("" if admins else
                      "; sin «Do not allow bypassing the above settings», un administrador puede unir con ellas en rojo"))
    return pr_sin, metodos, list(dict.fromkeys(c for c in checks if c)), checks_sin, ev


