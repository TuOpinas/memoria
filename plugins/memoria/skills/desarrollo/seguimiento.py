def ruta_segura(r):
    return bool(r) and not r.startswith(("/", "~")) and ".." not in r.replace("\\", "/").split("/")


def kit(raiz, proyecto):
    raiz = pathlib.Path(raiz)
    tp = leer(raiz / proyecto / "proyecto.md")
    if tp is None:
        raise SystemExit(f"no se pudo leer {proyecto}/proyecto.md")
    sec = seccion_desarrollo(tp)
    if not sec.found:
        raise SystemExit(f"{proyecto} no es un proyecto de desarrollo: su proyecto.md no tiene la sección «## Desarrollo» con las claves del kit")
    textos = {}
    for k, r in sec.paths.items():
        if r and r != TO_BUILD and ruta_segura(r):
            t = leer(raiz / r)
            if t is not None:
                textos[k] = (r, t)
    return tp, sec, textos


def ultimo_seguimiento(texto):
    m = re.search(r"^## (20\d\d-\d\d-\d\d)\b", cabecera(texto or "")[1], re.M)
    return m.group(1) if m else ""


def persona(sec, texto, roles):
    """La persona de esos roles que nombra un texto (por nombre, @usuario o correo), o None."""
    t = (texto or "").strip()
    usuario = t.lstrip("@").lower() if t.startswith("@") else ""
    for rol in roles:
        for p in sec.roles.get(rol, []):
            if (p.user and usuario == p.user.lower()) or (p.email and p.email == t.lower()) or nombre_key(p.name) == nombre_key(t):
                return p
    return None


