def leer(p):
    try:
        return pathlib.Path(p).read_text(encoding="utf-8-sig").replace("\r\n", "\n")
    except (OSError, UnicodeDecodeError):
        return None


def cabecera(texto):
    m = re.match(r"^---\n(.*?)\n---\n?", texto or "", re.S)
    if not m:
        return {}, texto or ""
    fm = {}
    for l in m.group(1).split("\n"):
        mm = re.match(r"^(\w+):\s*(.*)$", l)
        if mm:
            fm[mm.group(1)] = mm.group(2).strip().strip("'\"")
    return fm, texto[m.end():]


def celda(t):
    """Una celda de tabla de la memoria: sin saltos de línea ni «|»."""
    return re.sub(r"\s+", " ", str(t or "")).replace("|", "·").strip()


def corto(sha):
    return (sha or "")[:7]


def nombre_key(n):
    n = unicodedata.normalize("NFD", n or "")
    n = "".join(c for c in n if unicodedata.category(c) != "Mn")
    return re.sub(r"\s+", " ", re.sub(r"\([^)]*\)", "", n)).strip(" .,;:").lower()


