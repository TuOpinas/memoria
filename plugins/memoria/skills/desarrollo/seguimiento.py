def con_diseno(gh, diseno, migraciones_extra):
    """Lo que no está en el diseño: tablas nuevas que no están en «Datos», código nuevo fuera de los «Dónde vive» de
    «Componentes» y nombres que el diseño dice que no son un concepto («No es»), solo en nombres de archivo y en
    definiciones, no en palabras sueltas del código."""
    out = {"tablas": [], "fuera_de_componentes": [], "alias": []}
    def formas(n):
        k = key(n)
        return {k, k + "s", k + "es", (k[:-1] + "ies") if k.endswith("y") else k}
    entidades = set().union(*[formas(e.name) for e in diseno.entities]) if diseno.entities else set()
    # una tabla de unión de una N:M («order_tags») no es una entidad aparte
    for e in diseno.entities:
        for r in e.relations:
            if r.cardinality == "N:M":
                for a in formas(e.name):
                    for b in formas(r.target):
                        entidades |= {f"{a} {b}", f"{b} {a}"}
    alias = {}
    for c in diseno.concepts:
        for a in c.get("no_es", []):
            if key(a):
                alias[key(a)] = (a, c.get("concepto", ""))
    rutas = {}
    for c in diseno.components:
        for parte in re.split(r",\s*", c.get("donde_vive") or ""):
            m = re.match(r"^([\w.-]+/[\w.-]+)(?::(.*))?$", parte.strip())
            if m:
                rutas.setdefault(m.group(1).lower(), []).append((m.group(2) or "").strip().strip("/"))
            elif parte.strip() and rutas:
                rutas[list(rutas)[-1]].append(parte.strip().strip("/"))
    for r in gh.get("repos", []):
        nombre = r["repo"]
        sueltos = set()
        for d in r.get("detalle", []):
            for f in d.get("files", []):
                fn = f.get("filename", "")
                es_mig = es_migracion(fn, migraciones_extra)
                anadidas = "\n".join(l[1:] for l in (f.get("patch") or "").split("\n") if l.startswith("+") and not l.startswith("+++"))
                if es_mig and f.get("status") == "added":
                    for t in re.findall(r"create\s+(?:(?:temp|temporary|unlogged)\s+)?table\s+(?:if\s+not\s+exists\s+)?(?:[\w\"]+\.)?\"?(\w+)\"?", anadidas, re.I):
                        if key(t.replace("_", " ")) not in entidades and key(t) not in entidades and not re.match(r"^(alembic|schema|django|knex|flyway)_", t, re.I):
                            out["tablas"].append({"repo": nombre, "tabla": t, "archivo": fn, "commit": corto(d["sha"])})
                if f.get("status") == "added" and nombre.lower() in rutas and not IGNORADAS.match(fn) and "/" in fn and not es_mig:
                    if not any(not p or fn == p or fn.startswith(p + "/") for p in rutas[nombre.lower()]):
                        sueltos.add("/".join(fn.split("/")[:2 if fn.count("/") > 1 else 1]))
                if alias and not fn.lower().endswith((".md", ".lock")) and not es_mig:
                    # solo nombres que se definen o se nombran: el archivo, y clases, funciones y tablas nuevas
                    nombres = [pathlib.PurePosixPath(fn).stem] if f.get("status") == "added" else []
                    nombres += re.findall(r"\b(?:class|def|function|interface|type|struct|enum|const|let|var|table)\s+([A-Za-z_][\w]*)", anadidas)
                    trozos = set()
                    for w in nombres:
                        trozos.add(key(w))
                        trozos.update(key(x) for x in re.split(r"[_\-.]|(?<=[a-z])(?=[A-Z])", w) if x)
                    for k, (a, concepto) in alias.items():
                        if k in trozos or (" " in k and k in " ".join(trozos)):
                            out["alias"].append({"repo": nombre, "alias": a, "concepto": concepto, "archivo": fn, "commit": corto(d["sha"])})
        out["fuera_de_componentes"] += [{"repo": nombre, "ruta": s} for s in sorted(sueltos)]
