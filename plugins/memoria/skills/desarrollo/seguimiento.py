def prs_de(gh):
    out = []
    for r in gh.get("repos", []):
        for p in r.get("pulls", []):
            out.append(PullRequest(repo=r["repo"], number=int(p["number"]), title=p.get("title", ""), state=p.get("state", ""),
                                   author=p.get("author", ""), bot=bool(p.get("bot")), merge_commit=p.get("merge_commit", ""),
                                   to_main=not p.get("base") or p.get("base") == r.get("rama", "main")))
    return out


def historia(r):
    """{sha: posición} de la rama principal, 0 el más nuevo."""
    return {c["sha"]: i for i, c in enumerate(r.get("commits", []))}


def aprobado(rel):
    m = APROBO.search(rel.get("body") or "")
    if not m:
        return None
    t = m.group(1).strip()
    quien = re.split(r",|·", t)[0].strip()
    seg = re.search(r"seguimiento\s+(20\d\d-\d\d-\d\d)", t, re.I)
    return {"quien": quien, "texto": t, "seguimiento": seg.group(1) if seg else ""}


def pasos_a_prod(r, forma):
    """Los pasos a Prod de un repositorio, del más nuevo al más viejo: [{tag, sha, aprobo, fecha}]. Con «release de GitHub»,
    los releases publicados (no borradores); con otra forma, los releases y las etiquetas, que es lo único que deja ver
    qué se desplegó."""
    pos = historia(r)
    out = []
    for x in r.get("releases", []):
        if x.get("draft") or not x.get("sha"):
            continue
        out.append({"tag": x["tag"], "sha": x["sha"], "aprobo": aprobado(x), "fecha": (x.get("published_at") or "")[:10], "release": True})
    if key(forma) != key("release de GitHub"):
        vistos = {o["sha"] for o in out}
        for t in r.get("tags", []):
            if t.get("sha") and t["sha"] not in vistos:
                out.append({"tag": t["name"], "sha": t["sha"], "aprobo": None, "fecha": "", "release": False})
                vistos.add(t["sha"])
    out.sort(key=lambda o: pos.get(o["sha"], 10 ** 9))
    return out


def entregados(gh, forma):
    """{repo: números de los pull requests unidos dentro del último paso a Prod}. Con «release de GitHub», solo cuenta un
    release con «Aprobó:» (plantilla de la sección)."""
    out = {}
    for r in gh.get("repos", []):
        pasos = [p for p in pasos_a_prod(r, forma) if p["aprobo"] or key(forma) != key("release de GitHub")]
        pos = historia(r)
        if not pasos or pasos[0]["sha"] not in pos:
            continue
        corte = pos[pasos[0]["sha"]]
        out[r["repo"]] = [p["number"] for p in r.get("pulls", [])
                          if p.get("state") == "merged" and p.get("merge_commit") in pos and pos[p["merge_commit"]] >= corte]
    return out


