def poner_arriba(texto, nueva, fecha):
    fm, cuerpo = cabecera(texto)
    m = re.search(r"^## ", cuerpo, re.M)
    cab = texto[:len(texto) - len(cuerpo)]
    cab = re.sub(r"^actualizado:.*$", f"actualizado: {fecha}", cab, count=1, flags=re.M)
    if m:
        return cab + cuerpo[:m.start()] + nueva + "\n" + cuerpo[m.start():]
    return cab + cuerpo.rstrip() + "\n\n" + nueva


def linea_de_la_seccion(tp, clave):
    """La línea de una clave dentro de «## Desarrollo», tal cual, o None."""
    dentro = False
    for l in tp.split("\n"):
        if l.startswith("## "):
            dentro = key(l[3:]) == key(SECTION)
            continue
        if dentro and re.match(r"^[-*]?\s*\**\s*" + clave + r"\s*\**\s*:", l.strip(), re.I):
            return l
    return None


