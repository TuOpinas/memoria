def leer(p):
    k = str(p)
    if k not in _LEIDOS:
        try:
            _LEIDOS[k] = pathlib.Path(p).read_bytes().decode("utf-8-sig", errors="replace").replace("\r\n", "\n")
        except OSError:
            _LEIDOS[k] = None
    return _LEIDOS[k]


def cuerpo(t):
    m = re.match(r"^---\n.*?\n---\n?", t or "", re.S)
    return (t or "")[m.end():] if m else (t or "")


def seccion(t, nombre):
    m = re.search(r"^## " + re.escape(nombre) + r"\s*\n(.*?)(?=^## |\Z)", t or "", re.S | re.M)
    return m.group(1).strip() if m else None


def fecha_de(s):
    m = FECHA.search(s or "")
    if not m:
        return None
    try:
        return datetime.date.fromisoformat(m.group(1))
    except ValueError:
        return None


def version(v):
    m = re.match(r"(\d+)\.(\d+)\.(\d+)", v or "")
    return tuple(int(x) for x in m.groups()) if m else ()


def zona(guia):
    m = re.search(r"^\s*[-*]?\s*\**\s*zona horaria\s*\**\s*:\s*\**\s*`?\s*([A-Za-z0-9_+-]+(?:/[A-Za-z0-9_+-]+){0,2})", guia, re.M | re.I)
    try:
        from zoneinfo import ZoneInfo
    except Exception:
        return None
    for z in ([m.group(1)] if m and not m.group(1).startswith("[") else []) + ["America/Mexico_City"]:
        try:
            return ZoneInfo(z)
        except Exception:
            continue
    return None


def entradas(texto):
    """Las entradas «## …» de un registro, en el orden del archivo, con su fecha (como abrir.py)."""
    out = []
    for p in re.split(r"^(?=## )", texto or "", flags=re.M):
        if p.startswith("## "):
            cab = p.split("\n", 1)[0]
            out.append({"fecha": fecha_de(cab), "cab": cab[3:].strip(), "texto": p.rstrip()})
    return out


def con_ids(es):
    """Identificador de cada entrada: fecha y -2, -3… contando desde la más antigua del mismo día (de abajo arriba)."""
    cuenta = {}
    for e in reversed(es):
        if not e["fecha"]:
            e["id"] = ""
            continue
        n = cuenta[e["fecha"]] = cuenta.get(e["fecha"], 0) + 1
        e["id"] = e["fecha"].isoformat() + ("" if n == 1 else "-%d" % n)
    return es


def acotado(lineas, tema, tope, solo):
    if solo == tema or len(lineas) <= tope:
        return lineas
    return lineas[:tope] + ["… y %d más (el tema entero: --tema %s)" % (len(lineas) - tope, tema)]


