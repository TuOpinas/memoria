#!/usr/bin/env python3
"""Puts the package inside the plugin scripts that use it, so each one keeps working when downloaded alone.

Every script that has moved onto the package carries a region between `BEGIN` and `END`; this fills it with the
sources of the modules the scripts import (records, parse, compat), as strings loaded into `sys.modules` under
`memoria_core`. The committed scripts carry the region already filled, because the sessions download them from the
repository tag and check their hash: what is in the repository is what runs.

    python3 core/inline.py            # rewrite the region of every script that has one
    python3 core/inline.py --check    # exit 1 if any region is not what the package says (tests and release.sh)
"""
import pathlib, re, sys

CORE = pathlib.Path(__file__).resolve().parent
REPO = CORE.parent
MODULES = ["records", "parse", "compat"]
BEGIN = "# --- memoria_core: generated by core/inline.py from core/memoria_core; do not edit by hand ---"
END = "# --- end of memoria_core ---"
SCRIPTS = [REPO / "plugins" / "memoria" / "skills" / "sesion" / "abrir.py"]


def region() -> str:
    src = {m: (CORE / "memoria_core" / f"{m}.py").read_text(encoding="utf-8") for m in MODULES}
    body = ",\n".join(f"    {m!r}: {src[m]!r}" for m in MODULES)
    return f'''{BEGIN}
def _memoria_core():
    import sys as _s, types as _t
    if "memoria_core.compat" in _s.modules:
        return
    _src = {{
{body},
    }}
    _pkg = _t.ModuleType("memoria_core"); _pkg.__path__ = []; _s.modules["memoria_core"] = _pkg
    for _n in {MODULES!r}:
        _m = _t.ModuleType("memoria_core." + _n); _m.__package__ = "memoria_core"
        _s.modules[_m.__name__] = _m
        exec(compile(_src[_n], "<memoria_core/" + _n + ".py>", "exec"), _m.__dict__)
        setattr(_pkg, _n, _m)
_memoria_core()
{END}'''


def apply(text: str) -> str:
    a, b = text.index(BEGIN), text.index(END) + len(END)
    return text[:a] + region() + text[b:]


def main(argv):
    check = "--check" in argv
    stale = []
    for p in SCRIPTS:
        t = p.read_text(encoding="utf-8")
        new = apply(t)
        if new != t:
            stale.append(p.relative_to(REPO))
            if not check:
                p.write_text(new, encoding="utf-8")
    if check and stale:
        print("memoria_core is out of date in: " + ", ".join(map(str, stale)) + " (run core/inline.py)")
        return 1
    print(("up to date" if check else "rewritten: " + (", ".join(map(str, stale)) or "nothing")))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
